import { chromium } from 'playwright';
import fs from 'node:fs';
const OUT='assets/shots'; fs.mkdirSync(OUT,{recursive:true});
const b = await chromium.launch();
const ctx = await b.newContext({ viewport:{width:1440,height:900}, deviceScaleFactor:2, reducedMotion:'reduce' });
const p = await ctx.newPage();
await p.goto('file://'+process.cwd()+'/../site/index.html',{waitUntil:'load'});
await p.addStyleTag({content:'html{scroll-behavior:auto!important}.js .reveal{opacity:1!important;transform:none!important;transition:none!important}*{animation:none!important}.tick-draw{stroke-dashoffset:0!important}'});
await p.evaluate(()=>document.fonts.ready); await p.waitForTimeout(800);
const snap = async (sel, name, i=0) => {
  const el = p.locator(sel).nth(i);
  await el.scrollIntoViewIfNeeded(); await p.waitForTimeout(150);
  await el.screenshot({ path:`${OUT}/${name}.png` });
  const bb = await el.boundingBox(); console.log(name, Math.round(bb.width), Math.round(bb.height));
};
await snap('#site-header','header');
await snap('.hero','hero');
await snap('.register','register');
await snap('.hero h1','h1');
await snap('.hero .actions','actions');
await snap('.cred','cred');
await snap('.about','about');
for (let i=0;i<9;i++) await snap('.svc',`svc_${i}`,i);
await p.click('#svc-accounting-btn'); await p.waitForTimeout(900);
await snap('#svc-accounting','svc_open');
await p.click('#svc-accounting-btn'); await p.waitForTimeout(500);
await snap('.services','services');
await snap('.serve','serve');
for (let i=0;i<3;i++) await snap('.serve-row',`serve_${i}`,i);
await snap('.why','why');
for (let i=0;i<6;i++) await snap('.why-list li',`why_${i}`,i);
await snap('.lead-panel','lead');
await snap('.how','how');
for (let i=0;i<4;i++) await snap('#steps li',`step_${i}`,i);
await p.click('#faq-0-btn'); await p.waitForTimeout(900);
await snap('.faq','faq');
await snap('.contact','contact');
await snap('#enquiry','form');
await snap('.footer','footer');
await b.close();
